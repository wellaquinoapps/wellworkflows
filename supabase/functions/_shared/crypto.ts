// Secure AES-256-GCM encryption & decryption using Web Crypto API.
// Requires MASTER_ENCRYPTION_KEY environment secret (32-byte hex or 32+ char key).

async function getCryptoKey(): Promise<CryptoKey> {
  const secret = Deno.env.get("MASTER_ENCRYPTION_KEY");
  if (!secret) {
    throw new Error("MASTER_ENCRYPTION_KEY is not configured in environment secrets.");
  }

  // Derive a 256-bit key using SHA-256 from the provided secret
  const encoder = new TextEncoder();
  const keyMaterial = await crypto.subtle.digest("SHA-256", encoder.encode(secret));

  return await crypto.subtle.importKey(
    "raw",
    keyMaterial,
    { name: "AES-GCM" },
    false,
    ["encrypt", "decrypt"]
  );
}

/**
 * Encrypts a plaintext string (e.g. Gemini API Key) with AES-256-GCM.
 * Output format: base64(iv[12 bytes] + ciphertext + authTag[16 bytes])
 */
export async function encryptSecret(plainText: string): Promise<string> {
  if (!plainText || typeof plainText !== "string") {
    throw new Error("Invalid input to encryptSecret.");
  }

  const key = await getCryptoKey();
  const iv = crypto.getRandomValues(new Uint8Array(12)); // 96-bit IV standard for GCM
  const encoder = new TextEncoder();
  const encodedData = encoder.encode(plainText);

  const encryptedBuffer = await crypto.subtle.encrypt(
    {
      name: "AES-GCM",
      iv: iv,
    },
    key,
    encodedData
  );

  const encryptedBytes = new Uint8Array(encryptedBuffer);
  const combined = new Uint8Array(iv.length + encryptedBytes.length);
  combined.set(iv, 0);
  combined.set(encryptedBytes, iv.length);

  return btoa(String.fromCharCode(...combined));
}

/**
 * Decrypts an AES-256-GCM payload generated by encryptSecret.
 */
export async function decryptSecret(encryptedPayload: string): Promise<string> {
  if (!encryptedPayload) {
    throw new Error("Empty payload passed to decryptSecret.");
  }

  const key = await getCryptoKey();
  const binaryString = atob(encryptedPayload);
  const combined = new Uint8Array(binaryString.length);
  for (let i = 0; i < binaryString.length; i++) {
    combined[i] = binaryString.charCodeAt(i);
  }

  if (combined.length < 12 + 16) {
    throw new Error("Malformed encrypted payload.");
  }

  const iv = combined.slice(0, 12);
  const data = combined.slice(12);

  const decryptedBuffer = await crypto.subtle.decrypt(
    {
      name: "AES-GCM",
      iv: iv,
    },
    key,
    data
  );

  const decoder = new TextDecoder();
  return decoder.decode(decryptedBuffer);
}

/**
 * Masks an API key for safe UI display (e.g. AIzaSy...Abc4)
 */
export function maskApiKey(apiKey: string): string {
  if (!apiKey || apiKey.length < 8) return "••••••••";
  return `${apiKey.slice(0, 6)}••••••••${apiKey.slice(-4)}`;
}

